import org.springframework.transaction.annotation.Transactional;

/**
 * Institution-specific student numbering (no global format is assumed).
 * <ul>
 *   <li><b>GENERATED</b>: a template such as {@code {INST}{YYYY}{SEQ:4}} with tokens {@code {INST}} (institution code),
 *       {@code {YYYY}}, {@code {YY}} (admission year) and exactly one {@code {SEQ:n}} (3–8 digits, counted per year when
 *       the template contains a year, otherwise continuously).</li>
 *   <li><b>MANUAL</b>: the number is entered and must match a format mask.</li>
 * </ul>
 * Format masks (manual numbers and registration numbers) use {@code A} = letter, {@code 9} = digit, {@code X} = letter or
 * digit, {@code *} = one or more letters or digits; every other capital letter or digit and {@code / - . _} stand for
 * themselves (e.g. {@code MCC-9999}); masks are compiled to bounded
 * expressions, so administrators never supply raw regular expressions.
 * A college without a rule inherits its university's rule; without any rule, numbers are entered manually
 * (letters, digits and / - . _, 3–40 characters).
 */
@Service
public class StudentNumbering {

    public enum Mode { GENERATED, MANUAL }

    @Schema(name = "StudentNumberRule")
    public record RuleView(UUID orgUnitId, String orgUnitName, String orgUnitType, boolean configured, UUID inheritedFrom, Mode mode, String template,
                           String manualPattern, String registrationPattern, String example, long version, boolean canManage) {}

    public record RuleCommand(Mode mode, String template, String manualPattern, String registrationPattern, Long version) {}

    private static final Pattern TOKEN = Pattern.compile("\\{(INST|YYYY|YY|SEQ:([3-8]))}");
    private static final Pattern TEMPLATE_LITERALS = Pattern.compile("[A-Za-z0-9/_.-]*");
    private static final Pattern MASK = Pattern.compile("^[A-Z0-9*/_.-]{1,40}$");
    static final Pattern DEFAULT_NUMBER = Pattern.compile("^[A-Za-z0-9][A-Za-z0-9/_.-]{2,39}$");

    private final JdbcClient jdbc;
    private final StudentAccess access;
    private final AuditLog audit;

    StudentNumbering(JdbcClient jdbc, StudentAccess access, AuditLog audit) {
        this.jdbc = jdbc;
        this.access = access;
        this.audit = audit;
    }

    record Rule(UUID id, UUID orgUnitId, Mode mode, String template, String manualPattern, String registrationPattern, long version) {}

    Optional<Rule> ruleOf(UUID orgUnitId) {
        return jdbc.sql("SELECT id, org_unit_id, mode, template, manual_pattern, registration_pattern, version FROM student_number_rule WHERE org_unit_id = ?")
                .param(orgUnitId).query((rs, n) -> new Rule(rs.getObject(1, UUID.class), rs.getObject(2, UUID.class), Mode.valueOf(rs.getString(3)),
                        rs.getString(4), rs.getString(5), rs.getString(6), rs.getLong(7))).optional();
    }

    /** The rule in force for an institution: its own, else its university's. */
    Optional<Rule> effective(UUID institutionId) {
        Optional<Rule> own = ruleOf(institutionId);
        if (own.isPresent()) return own;
        return access.unit(institutionId).map(StudentAccess.Unit::parentId).flatMap(this::ruleOf);
    }

    /** Student number for a new student: generated by the rule or validated against it. */
    String assign(UUID institutionId, String requested, Integer admissionYear) {
        Optional<Rule> rule = effective(institutionId);
        if (rule.isPresent() && rule.get().mode() == Mode.GENERATED) {
            if (requested != null && !requested.isBlank()) {
                throw ApiException.badRequest("student_no_generated", "Student IDs are generated for this institution; leave the field empty.");
            }
            return generate(rule.get(), institutionId, admissionYear == null ? Year.now().getValue() : admissionYear);
        }
        String no = requested == null ? "" : requested.trim();
        if (no.isEmpty()) throw ApiException.badRequest("invalid_studentNo", "Enter the student ID.");
        Pattern p = rule.map(r -> r.manualPattern() == null ? DEFAULT_NUMBER : compileMask(r.manualPattern())).orElse(DEFAULT_NUMBER);
        if (!p.matcher(no).matches()) {
            throw ApiException.badRequest("invalid_studentNo", "The student ID does not match the institution's format"
                    + rule.map(r -> r.manualPattern() == null ? "" : " (" + r.manualPattern() + ")").orElse("") + ".");
        }
        return no;
    }

    void validateRegistration(UUID institutionId, String registrationNo) {
        if (registrationNo == null) return;
        Optional<String> mask = effective(institutionId).map(Rule::registrationPattern);
        Pattern p = mask.map(StudentNumbering::compileMask).orElse(DEFAULT_NUMBER);
        if (!p.matcher(registrationNo).matches()) {
            throw ApiException.badRequest("invalid_registrationNo", "The registration number does not match the institution's format"
                    + mask.map(m -> " (" + m + ")").orElse("") + ".");
        }
    }

    private String generate(Rule rule, UUID institutionId, int year) {
        String inst = access.unit(institutionId).map(StudentAccess.Unit::code).orElse("").toUpperCase().replaceAll("[^A-Z0-9]", "");
        String period = rule.template().contains("{YY") ? String.valueOf(year) : "ALL";
        for (int attempt = 0; attempt < 50; attempt++) {
            long seq = jdbc.sql("""
                    INSERT INTO student_number_counter (tenant_id, rule_id, period, next_value) VALUES (?, ?, ?, 2)
                    ON CONFLICT (tenant_id, rule_id, period) DO UPDATE SET next_value = student_number_counter.next_value + 1
                    RETURNING next_value - 1""").params(tenant(), rule.id(), period).query(Long.class).single();
            String no = render(rule.template(), inst, year, seq);
            if (no.length() > 40) throw invalid("student_no_too_long", "The numbering template produces IDs longer than 40 characters.");
            boolean taken = jdbc.sql("SELECT count(*) FROM student WHERE lower(student_no) = lower(?)").param(no).query(Long.class).single() > 0;
            if (!taken) return no;
        }
        throw StudentAccess.conflict("student_no_exhausted", "No free student ID could be generated; check the numbering rule.");
    }

    static String render(String template, String inst, int year, long seq) {
        Matcher m = TOKEN.matcher(template);
        StringBuilder out = new StringBuilder();
        while (m.find()) {
            String value = switch (m.group(1)) {
                case "INST" -> inst;
                case "YYYY" -> String.valueOf(year);
                case "YY" -> String.format("%02d", year % 100);
                default -> {
                    int width = Integer.parseInt(m.group(2));
                    String s = String.valueOf(seq);
                    if (s.length() > width) throw invalid("sequence_exhausted", "The sequence of the numbering rule has run out of digits.");
                    yield "0".repeat(width - s.length()) + s;
                }
            };
            m.appendReplacement(out, Matcher.quoteReplacement(value));
        }
        m.appendTail(out);
        return out.toString();
    }

    static void validateTemplate(String template) {
        if (template == null || template.isBlank() || template.length() > 100) throw ApiException.badRequest("invalid_template", "Enter a template of at most 100 characters.");
        Matcher m = TOKEN.matcher(template);
        int seq = 0;
        StringBuilder literals = new StringBuilder();
        int last = 0;
        while (m.find()) {
            literals.append(template, last, m.start());
            last = m.end();
            if (m.group(1).startsWith("SEQ")) seq++;
        }
        literals.append(template.substring(last));
        if (seq != 1) throw ApiException.badRequest("invalid_template", "The template needs exactly one {SEQ:n} token (n = 3 to 8).");
        if (!TEMPLATE_LITERALS.matcher(literals).matches()) {
            throw ApiException.badRequest("invalid_template", "Use only {INST}, {YYYY}, {YY}, {SEQ:n}, letters, digits and / - . _");
        }
    }

    /** Compiles a format mask to a bounded expression (no user-supplied regular expressions). */
    static Pattern compileMask(String mask) {
        if (mask == null || !MASK.matcher(mask).matches() || mask.chars().filter(c -> c == '*').count() > 1) {
            throw ApiException.badRequest("invalid_pattern", "Use A (letter), 9 (digit), X (letter or digit), one * (several letters or digits), other capital letters "
                    + "and digits as written, and / - . _ (at most 40).");
        }
        StringBuilder re = new StringBuilder("^");
        for (char c : mask.toCharArray()) {
            re.append(switch (c) {
                case 'A' -> "[A-Za-z]";
                case '9' -> "[0-9]";
                case 'X' -> "[A-Za-z0-9]";
                case '*' -> "[A-Za-z0-9]{1,40}";
                default -> Pattern.quote(String.valueOf(c));
            });
        }
        return Pattern.compile(re.append("$").toString());
    }

    // ------------------------------------------------------------------------------------------------ rule management

    private static final Set<String> INSTITUTIONS = Set.of("UNIVERSITY", "COLLEGE");

    @Transactional(readOnly = true)
    public List<RuleView> rules() {
        access.requireAnyRead();
        List<RuleView> out = new ArrayList<>();
        List<UUID> units = jdbc.sql("SELECT id FROM org_unit WHERE unit_type IN ('UNIVERSITY', 'COLLEGE') AND status = 'ACTIVE' ORDER BY path").query(UUID.class).list();
        for (UUID u : units) {
            if (!access.can(StudentAccess.READ, u)) continue;
            out.add(view(u));
        }
        return out;
    }

    RuleView view(UUID unitId) {
        StudentAccess.Unit unit = access.unit(unitId).orElseThrow(() -> ApiException.notFound("Unit"));
        Optional<Rule> own = ruleOf(unitId);
        Optional<Rule> eff = own.isPresent() ? own : effective(unitId);
        String example;
        if (eff.isPresent() && eff.get().mode() == Mode.GENERATED) {
            example = render(eff.get().template(), unit.code().toUpperCase().replaceAll("[^A-Z0-9]", ""), Year.now().getValue(), 1);
        } else {
            example = eff.map(Rule::manualPattern).orElse(null);
        }
        return new RuleView(unitId, unit.name(), unit.type(), own.isPresent(), own.isPresent() ? null : eff.map(Rule::orgUnitId).orElse(null),
                eff.map(Rule::mode).orElse(Mode.MANUAL), eff.map(Rule::template).orElse(null), eff.map(Rule::manualPattern).orElse(null),
                eff.map(Rule::registrationPattern).orElse(null), example, own.map(Rule::version).orElse(-1L), access.can(StudentAccess.MANAGE, unitId));
    }

    @Transactional
    public RuleView save(UUID unitId, RuleCommand c) {
        StudentAccess.Unit unit = access.unit(unitId).orElseThrow(() -> invalid("invalid_orgUnitId", "Choose a university or college."));
        if (!INSTITUTIONS.contains(unit.type())) throw invalid("invalid_orgUnitId", "Numbering rules belong to a university or college.");
        access.requireAt(StudentAccess.MANAGE, unitId);
        if (c.mode() == null) throw ApiException.badRequest("invalid_mode", "Choose generated or manual numbering.");
        String template = c.mode() == Mode.GENERATED ? c.template() == null ? null : c.template().trim() : null;
        if (c.mode() == Mode.GENERATED) validateTemplate(template);
        String manual = c.mode() == Mode.MANUAL ? blankToNull(c.manualPattern()) : null;
        if (manual != null) compileMask(manual);
        String registration = blankToNull(c.registrationPattern());
        if (registration != null) compileMask(registration);
        Optional<Rule> existing = ruleOf(unitId);
        if (existing.isPresent()) {
            jdbc.sql("SELECT 1 FROM student_number_rule WHERE id = ? FOR UPDATE").param(existing.get().id()).query(Integer.class).single();
            StudentAccess.version(c.version(), ruleOf(unitId).orElseThrow().version());
            jdbc.sql("UPDATE student_number_rule SET mode = ?, template = ?, manual_pattern = ?, registration_pattern = ?, updated_at = now(), updated_by = ?, version = version + 1 WHERE id = ?")
                    .params(c.mode().name(), template, manual, registration, actor(), existing.get().id()).update();
        } else {
            if (c.version() != null && c.version() != -1L) StudentAccess.version(c.version(), -1L);
            jdbc.sql("INSERT INTO student_number_rule (id, tenant_id, org_unit_id, mode, template, manual_pattern, registration_pattern, updated_by) VALUES (?, ?, ?, ?, ?, ?, ?, ?)")
                    .params(Ids.newId(), tenant(), unitId, c.mode().name(), template, manual, registration, actor()).update();
        }
        Map<String, String> d = new LinkedHashMap<>();
        d.put("orgUnitId", unitId.toString());
        d.put("mode", c.mode().name());
        if (template != null) d.put("template", template);
        if (manual != null) d.put("manualPattern", manual);
        if (registration != null) d.put("registrationPattern", registration);
        audit.recordSuccess("student.numbering_rule.saved", "student_number_rule", unitId.toString(), d);
        return view(unitId);
    }

    private static String blankToNull(String s) {
        return s == null || s.isBlank() ? null : s.trim();
    }
}
